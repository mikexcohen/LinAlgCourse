"""Rebuild the combined course notebook from the maintained allCode notebooks."""
import argparse
import copy
import hashlib
from pathlib import Path

import nbformat

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'LinAlgCourse_allCode_combined.ipynb'


def source_paths(root=ROOT):
    return sorted(p for p in root.rglob('*allCode.ipynb')
                  if '.ipynb_checkpoints' not in p.parts)


def concatenate(output=OUTPUT, root=ROOT):
    paths = source_paths(root)
    if not paths:
        raise ValueError('No allCode notebooks found.')
    contents = '# Linear algebra — combined allCode notebooks\n\n'
    contents += ('Generated by `tools/concatenate_notebooks.py` from the corrected '
                 'Python notebooks in this checkout. Run from the repository root. '
                 'Sections follow alphabetical repository-path order.\n\n')
    contents += '\n'.join(f'{i}. [{p.relative_to(root)}](#source-{i})'
                          for i, p in enumerate(paths, 1))
    cells = [nbformat.v4.new_markdown_cell(contents, id='course-contents')]
    sources = []
    for i, path in enumerate(paths, 1):
        relative = path.relative_to(root).as_posix()
        original = nbformat.read(path, as_version=4)
        nbformat.validate(original)
        cells.append(nbformat.v4.new_markdown_cell(
            f'<a id="source-{i}"></a>\n\n## {relative}', id=f'source-{i}'))
        start = len(cells)
        for index, cell in enumerate(original.cells):
            cell = copy.deepcopy(cell)
            cell.id = hashlib.sha256(f'{relative}:{index}'.encode()).hexdigest()[:16]
            if cell.cell_type == 'code':
                cell.outputs = []
                cell.execution_count = None
            cells.append(cell)
        sources.append(dict(path=relative, sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                            start_cell_index=start, cell_count=len(original.cells)))
    metadata = dict(kernelspec=dict(display_name='Python 3', language='python', name='python3'),
                    language_info=dict(name='python'),
                    concatenation=dict(sources=sources, order='alphabetical repository path'))
    combined = nbformat.v4.new_notebook(cells=cells, metadata=metadata)
    nbformat.validate(combined)
    nbformat.write(combined, output)
    # Catch omissions or accidental source modifications in the generated artifact.
    for source in sources:
        original = nbformat.read(root / source['path'], as_version=4)
        for offset, cell in enumerate(original.cells):
            merged = combined.cells[source['start_cell_index'] + offset]
            assert merged.source == cell.source
            assert merged.cell_type == cell.cell_type
    return combined


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    args = parser.parse_args()
    notebook = concatenate(args.output)
    print(f'Combined {len(notebook.metadata.concatenation.sources)} notebooks, '
          f'{len(notebook.cells)} cells: {args.output}')
